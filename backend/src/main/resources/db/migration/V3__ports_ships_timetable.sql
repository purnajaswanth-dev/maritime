ALTER TABLE departures ADD COLUMN IF NOT EXISTS seats_available INT DEFAULT 250;
ALTER TABLE departures ADD COLUMN IF NOT EXISTS service_id BIGINT;

-- 6. Create announcements table
CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(128) NOT NULL,
    body TEXT NOT NULL,
    severity VARCHAR(32) NOT NULL DEFAULT 'INFO', -- INFO, WARNING, CRITICAL
    scope VARCHAR(32) NOT NULL DEFAULT 'ALL',     -- ALL, PORT, ROUTE, DEPARTURE
    target_id VARCHAR(64),
    starts_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE,
    created_by VARCHAR(128) NOT NULL DEFAULT 'SYSTEM',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_announcements_active ON announcements(starts_at, ends_at);
CREATE INDEX IF NOT EXISTS idx_announcements_scope ON announcements(scope, target_id);
