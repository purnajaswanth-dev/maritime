-- 4. Create services table (timetable service patterns)
CREATE TABLE IF NOT EXISTS services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id VARCHAR(64) NOT NULL REFERENCES routes(id),
    vessel_id VARCHAR(64) NOT NULL REFERENCES vessels(id),
    departure_time TIME NOT NULL,
    duration_min DOUBLE PRECISION NOT NULL,
    days_of_week VARCHAR(64) NOT NULL DEFAULT '1,2,3,4,5,6,7', -- 1=Monday to 7=Sunday
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    base_fare NUMERIC(10, 2) NOT NULL DEFAULT 25.00,
    capacity INT NOT NULL DEFAULT 300,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_services_route ON services(route_id);
CREATE INDEX IF NOT EXISTS idx_services_vessel ON services(vessel_id);
CREATE INDEX IF NOT EXISTS idx_services_active ON services(active);

-- 5. Upgrade departures table
