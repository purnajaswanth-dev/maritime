-- =============================================================================
-- Where Is My Ferry? Database Schema
-- V1__initial_schema.sql
-- Compatible with PostgreSQL 16+ and H2 (PostgreSQL compatibility mode)
-- =============================================================================

-- 1. Ports
CREATE TABLE IF NOT EXISTS ports (
    id VARCHAR(64) PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Europe/Paris',
    amenities TEXT,
    berth_count INT NOT NULL DEFAULT 1
);

-- 2. Vessels
CREATE TABLE IF NOT EXISTS vessels (
    id VARCHAR(64) PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    mmsi VARCHAR(32),
    imo VARCHAR(32),
    capacity_passengers INT NOT NULL,
    capacity_vehicles INT NOT NULL DEFAULT 0,
    speed_knots DOUBLE PRECISION NOT NULL,
    tracking_vessel_id VARCHAR(64),
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE'
);

-- 3. Routes
CREATE TABLE IF NOT EXISTS routes (
    id VARCHAR(64) PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    origin_port_id VARCHAR(64) NOT NULL REFERENCES ports(id),
    destination_port_id VARCHAR(64) NOT NULL REFERENCES ports(id),
    name VARCHAR(128) NOT NULL,
    distance_nm DOUBLE PRECISION,
    crossing_duration_minutes DOUBLE PRECISION NOT NULL,
    tracking_supported BOOLEAN NOT NULL DEFAULT FALSE
);

-- 4. Schedules
CREATE TABLE IF NOT EXISTS schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id VARCHAR(64) NOT NULL,
    trip_id VARCHAR(64) NOT NULL UNIQUE,
    route_id VARCHAR(64) NOT NULL REFERENCES routes(id),
    vessel_id VARCHAR(64) NOT NULL REFERENCES vessels(id),
    departure_time TIME NOT NULL,
    arrival_time TIME NOT NULL,
    monday BOOLEAN NOT NULL DEFAULT TRUE,
    tuesday BOOLEAN NOT NULL DEFAULT TRUE,
    wednesday BOOLEAN NOT NULL DEFAULT TRUE,
    thursday BOOLEAN NOT NULL DEFAULT TRUE,
    friday BOOLEAN NOT NULL DEFAULT TRUE,
    saturday BOOLEAN NOT NULL DEFAULT TRUE,
    sunday BOOLEAN NOT NULL DEFAULT TRUE,
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 5. Departures (Historical & Live Scheduled Sailings)
CREATE TABLE IF NOT EXISTS departures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_code VARCHAR(64) NOT NULL UNIQUE,
    route_id VARCHAR(64) NOT NULL REFERENCES routes(id),
    vessel_id VARCHAR(64) NOT NULL REFERENCES vessels(id),
    scheduled_departure_time TIMESTAMP WITH TIME ZONE NOT NULL,
    scheduled_arrival_time TIMESTAMP WITH TIME ZONE NOT NULL,
    actual_departure_time TIMESTAMP WITH TIME ZONE,
    actual_arrival_time TIMESTAMP WITH TIME ZONE,
    status VARCHAR(32) NOT NULL DEFAULT 'SCHEDULED',
    delay_minutes INT DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vessel_scheduled_time UNIQUE (vessel_id, scheduled_departure_time)
);

CREATE INDEX IF NOT EXISTS idx_departures_sched_dep ON departures(scheduled_departure_time);
CREATE INDEX IF NOT EXISTS idx_departures_route_sched ON departures(route_id, scheduled_departure_time);
CREATE INDEX IF NOT EXISTS idx_departures_status ON departures(status);

-- 6. Fare Rules
CREATE TABLE IF NOT EXISTS fare_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id VARCHAR(64) NOT NULL REFERENCES routes(id),
    passenger_type VARCHAR(32) NOT NULL,
    vehicle_type VARCHAR(32),
    base_price_eur NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'EUR',
    valid_from DATE,
    valid_to DATE
);

-- 7. Users
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(128) NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL,
    first_name VARCHAR(64),
    last_name VARCHAR(64),
    phone VARCHAR(32),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 8. Roles
CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL UNIQUE
);

-- 9. User Roles Join Table
CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

-- 10. Bookings
CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR(32) NOT NULL UNIQUE,
    user_id BIGINT REFERENCES users(id),
    departure_id BIGINT NOT NULL REFERENCES departures(id),
    return_departure_id BIGINT REFERENCES departures(id),
    status VARCHAR(32) NOT NULL DEFAULT 'CONFIRMED',
    total_amount_eur NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'EUR',
    payment_status VARCHAR(32) NOT NULL DEFAULT 'PAID',
    contact_email VARCHAR(128) NOT NULL,
    contact_phone VARCHAR(32),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id);
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS departure_id BIGINT REFERENCES departures(id);

CREATE INDEX IF NOT EXISTS idx_bookings_user ON bookings(user_id);
CREATE INDEX IF NOT EXISTS idx_bookings_dep ON bookings(departure_id);

-- 11. Passengers
CREATE TABLE IF NOT EXISTS passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    first_name VARCHAR(64) NOT NULL,
    last_name VARCHAR(64) NOT NULL,
    passenger_type VARCHAR(32) NOT NULL,
    vehicle_type VARCHAR(32),
    vehicle_registration VARCHAR(32)
);

ALTER TABLE passengers ADD COLUMN IF NOT EXISTS booking_id BIGINT REFERENCES bookings(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_passengers_booking ON passengers(booking_id);

-- 12. Tickets
CREATE TABLE IF NOT EXISTS tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    passenger_id BIGINT NOT NULL REFERENCES passengers(id) ON DELETE CASCADE,
    ticket_number VARCHAR(64) NOT NULL UNIQUE,
    qr_code_data TEXT NOT NULL,
    barcode VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'VALID',
    issued_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tickets_booking ON tickets(booking_id);

-- 13. Payments (Honest simulation flag)
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    payment_intent_id VARCHAR(128) NOT NULL UNIQUE,
    amount_eur NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'EUR',
    status VARCHAR(32) NOT NULL DEFAULT 'COMPLETED',
    payment_method VARCHAR(32) NOT NULL DEFAULT 'CARD',
    simulated BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 14. Disruptions
CREATE TABLE IF NOT EXISTS disruptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id VARCHAR(64) REFERENCES routes(id),
    departure_id BIGINT REFERENCES departures(id),
    title VARCHAR(256) NOT NULL,
    description TEXT NOT NULL,
    severity VARCHAR(32) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_disruptions_route ON disruptions(route_id);

-- 15. Notifications
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(256) NOT NULL,
    message TEXT NOT NULL,
    channel VARCHAR(32) NOT NULL DEFAULT 'IN_APP',
    status VARCHAR(32) NOT NULL DEFAULT 'SENT',
    sent_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 16. Support Tickets
CREATE TABLE IF NOT EXISTS support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    booking_reference VARCHAR(32),
    subject VARCHAR(256) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    priority VARCHAR(32) NOT NULL DEFAULT 'NORMAL',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 17. Audit Logs
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    action VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64),
    entity_id VARCHAR(64),
    details TEXT,
    ip_address VARCHAR(45),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 18. Crew Assignments
CREATE TABLE IF NOT EXISTS crew_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id BIGINT NOT NULL REFERENCES departures(id) ON DELETE CASCADE,
    vessel_id VARCHAR(64) NOT NULL REFERENCES vessels(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role VARCHAR(64) NOT NULL,
    assigned_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 19. Maintenance Records
CREATE TABLE IF NOT EXISTS maintenance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vessel_id VARCHAR(64) NOT NULL REFERENCES vessels(id),
    title VARCHAR(256) NOT NULL,
    description TEXT,
    maintenance_type VARCHAR(64) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    status VARCHAR(32) NOT NULL DEFAULT 'PLANNED',
    cost_eur NUMERIC(10, 2)
);

-- 20. Share Links
CREATE TABLE IF NOT EXISTS share_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id BIGINT NOT NULL REFERENCES departures(id) ON DELETE CASCADE,
    token VARCHAR(128) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 21. ETA Accuracy Records
CREATE TABLE IF NOT EXISTS eta_accuracy_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id BIGINT NOT NULL REFERENCES departures(id) ON DELETE CASCADE,
    timestamp_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    predicted_minutes_to_arrival DOUBLE PRECISION,
    actual_remaining_minutes DOUBLE PRECISION,
    error_minutes DOUBLE PRECISION,
    distance_to_berth_km DOUBLE PRECISION
);
